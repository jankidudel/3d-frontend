import { TestBed } from '@angular/core/testing';
import { Job } from '../../../models/job';
import { StlQualityPdfService } from './stl-quality-pdf.service';

describe('StlQualityPdfService', () => {
  const validJob: Job = {
    id: 'job-1',
    fileName: 'gear housing.stl',
    fileSizeBytes: 22284,
    status: 'completed',
    createdAt: '2026-08-20T12:00:00Z',
    report: {
      fileName: 'gear housing.stl',
      fileSizeBytes: 22284,
      triangleCount: 444,
      dimensions: { width: 5, height: 20, depth: 4.35 },
      surfaceArea: 343.889,
      volume: 362.606,
      boundingBox: {
        minX: 15.5,
        minY: -10,
        minZ: 10.9,
        maxX: 20.5,
        maxY: 10,
        maxZ: 15.3,
      },
      validation: { isValid: true, issues: [] },
    },
  };

  it('creates a readable valid-report PDF with a safe filename', async () => {
    const service = TestBed.inject(StlQualityPdfService);

    const result = await service.createReport({
      ...validJob,
      report: {
        ...(validJob.report as object),
        fileName: 'My unsafe/model.stl',
      },
    });

    expect(result?.fileName).toBe('My-unsafe-model-quality-report.pdf');
    const contents = result?.pdf.output() ?? '';
    expect(contents).toContain('%PDF-');
    expect(contents).toContain('STL Quality Check Report');
    expect(contents).toContain('Model passed validation');
    expect(contents).toContain('No mesh validation issues found.');
    expect(contents).toContain('Generated by STL Quality Check');
  });

  it('includes several invalid findings and adds pages for long issue lists', async () => {
    const service = TestBed.inject(StlQualityPdfService);
    const issues = Array.from({ length: 45 }, (_, index) => ({
      code: index % 2 === 0 ? 'non_manifold_edge' : 'degenerate_triangle',
      count: index + 1,
      message: `Issue ${index + 1} needs attention before slicing this model.`,
    }));

    const result = await service.createReport({
      ...validJob,
      report: {
        ...(validJob.report as object),
        validation: { isValid: false, issues },
      },
    });

    const contents = result?.pdf.output() ?? '';
    expect(contents).toContain('Problems found');
    expect(contents).toContain('Non-manifold edges');
    expect(contents).toContain('Degenerate triangles');
    expect(contents).toContain(
      'Issue 45 needs attention before slicing this model.',
    );
    expect(result?.pdf.getNumberOfPages()).toBeGreaterThan(1);
  });

  it('includes the component count when topology is supplied', async () => {
    const service = TestBed.inject(StlQualityPdfService);
    const result = await service.createReport({
      ...validJob,
      report: {
        ...(validJob.report as object),
        topology: { connectedComponentCount: 2 },
      },
    });

    expect(result?.pdf.output()).toContain('2 separate components');
  });
});
