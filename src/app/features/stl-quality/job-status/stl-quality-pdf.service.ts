import { Service } from '@angular/core';
import { Job } from '../../../models/job';
import {
  guidanceForIssues,
  normalizeValidationIssues,
} from './validation-issues';

interface ReportRecord {
  [key: string]: unknown;
}

@Service()
export class StlQualityPdfService {
  async download(job: Job): Promise<void> {
    const report = await this.createReport(job);
    report?.pdf.save(report.fileName);
  }

  async createReport(
    job: Job,
  ): Promise<{ fileName: string; pdf: import('jspdf').jsPDF } | null> {
    const report = this.asRecord(job.report);
    if (!report) {
      return null;
    }

    const { jsPDF } = await import('jspdf');
    const pdf = new jsPDF({ compress: false, format: 'a4', unit: 'mm' });
    const pageWidth = pdf.internal.pageSize.getWidth();
    const pageHeight = pdf.internal.pageSize.getHeight();
    pdf.setCharSpace(0);
    const margin = 16;
    const contentWidth = pageWidth - margin * 2;
    const footerHeight = 14;
    let cursorY = margin;

    const addFooter = (pageNumber: number, pageCount: number): void => {
      pdf.setDrawColor(203, 215, 206);
      pdf.line(
        margin,
        pageHeight - footerHeight,
        pageWidth - margin,
        pageHeight - footerHeight,
      );
      pdf.setFontSize(8);
      pdf.setTextColor(82, 96, 87);
      pdf.text('Generated by 3D Quality Tools', margin, pageHeight - 8);
      pdf.text(
        `Page ${pageNumber} of ${pageCount}`,
        pageWidth - margin,
        pageHeight - 8,
        {
          align: 'right',
        },
      );
    };

    const newPage = (): void => {
      pdf.addPage();
      cursorY = margin;
    };

    const ensureSpace = (height: number): void => {
      if (cursorY + height > pageHeight - footerHeight - 4) {
        newPage();
      }
    };

    const writeLines = (
      text: string,
      options: {
        color?: [number, number, number];
        fontSize?: number;
        indent?: number;
        style?: 'bold' | 'normal';
      } = {},
    ): void => {
      const fontSize = options.fontSize ?? 10;
      const indent = options.indent ?? 0;
      const lineHeight = fontSize * 0.48;
      pdf.setFont('helvetica', options.style ?? 'normal');
      pdf.setFontSize(fontSize);
      pdf.setTextColor(...(options.color ?? [23, 33, 27]));
      const lines = pdf.splitTextToSize(text, contentWidth - indent);
      for (const line of lines) {
        ensureSpace(lineHeight);
        pdf.text(line, margin + indent, cursorY);
        cursorY += lineHeight;
      }
    };

    const heading = (text: string): void => {
      cursorY += 4;
      ensureSpace(14);
      writeLines(text, { color: [22, 101, 52], fontSize: 15, style: 'bold' });
      cursorY += 2;
    };

    const metricGrid = (fields: readonly [string, string][]): void => {
      const gap = 4;
      const columnWidth = (contentWidth - gap) / 2;
      const rowHeight = 20;
      for (let index = 0; index < fields.length; index += 2) {
        ensureSpace(rowHeight + gap);
        for (let column = 0; column < 2; column++) {
          const field = fields[index + column];
          if (!field) {
            continue;
          }
          const x = margin + column * (columnWidth + gap);
          pdf.setFillColor(244, 247, 245);
          pdf.roundedRect(x, cursorY, columnWidth, rowHeight, 2, 2, 'F');
          pdf.setFont('helvetica', 'bold');
          pdf.setFontSize(8);
          pdf.setTextColor(82, 96, 87);
          pdf.text(field[0], x + 3, cursorY + 6);
          pdf.setFont('helvetica', 'normal');
          pdf.setFontSize(10);
          pdf.setTextColor(23, 33, 27);
          const value = pdf
            .splitTextToSize(field[1], columnWidth - 6)
            .slice(0, 2);
          pdf.text(value, x + 3, cursorY + 12);
        }
        cursorY += rowHeight + gap;
      }
    };

    const validation = this.asRecord(report['validation']);
    const isValid = validation?.['isValid'] === true;
    const dimensions = this.asRecord(report['dimensions']);
    const boundingBox = this.asRecord(report['boundingBox']);
    const topology = this.asRecord(report['topology']);
    const issues = normalizeValidationIssues(validation?.['issues']);
    const fileName = this.stringValue(report['fileName']) || job.fileName;
    const fileSize = this.formatFileSize(
      report['fileSizeBytes'] ?? job.fileSizeBytes,
    );

    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(26);
    pdf.setTextColor(23, 33, 27);
    pdf.text('3D Quality Tools', margin, cursorY);
    cursorY += 9;
    pdf.setFontSize(15);
    pdf.setTextColor(22, 101, 52);
    pdf.text('STL Quality Check Report', margin, cursorY);
    cursorY += 7;
    writeLines(`Generated ${new Date().toLocaleString()}`, {
      color: [82, 96, 87],
      fontSize: 9,
    });
    cursorY += 5;

    const warningsOnly =
      issues.length > 0 &&
      issues.every((issue) => issue.severity === 'warning');
    const passed = isValid && !warningsOnly;
    const statusColor: [number, number, number] = isValid
      ? warningsOnly
        ? [151, 102, 0]
        : [20, 83, 45]
      : [143, 29, 20];
    const statusTitle = passed
      ? 'Model passed validation'
      : warningsOnly
        ? 'Warnings found'
        : 'Problems found';
    ensureSpace(29);
    pdf.setFillColor(
      isValid ? 232 : warningsOnly ? 255 : 253,
      isValid ? 245 : warningsOnly ? 246 : 236,
      isValid ? 236 : warningsOnly ? 222 : 234,
    );
    pdf.roundedRect(margin, cursorY, contentWidth, 25, 3, 3, 'F');
    pdf.setDrawColor(...statusColor);
    pdf.setLineWidth(1);
    pdf.line(margin, cursorY + 2, margin, cursorY + 23);
    if (passed) {
      pdf.line(margin + 4, cursorY + 13, margin + 7, cursorY + 16);
      pdf.line(margin + 7, cursorY + 16, margin + 13, cursorY + 8);
    } else {
      pdf.line(margin + 5, cursorY + 8, margin + 11, cursorY + 16);
      pdf.line(margin + 11, cursorY + 8, margin + 5, cursorY + 16);
    }
    writeLines(statusTitle, {
      color: statusColor,
      fontSize: 14,
      style: 'bold',
      indent: 17,
    });
    writeLines(
      passed
        ? 'No mesh validation issues were detected. This does not guarantee printability.'
        : warningsOnly
          ? 'Review the warnings before slicing. They may be intentional.'
          : 'Review the findings and repair guidance before slicing.',
      { color: [82, 96, 87], fontSize: 9, indent: 17 },
    );
    cursorY += 5;
    heading('File and model metrics');
    const componentCount = topology?.['connectedComponentCount'];
    metricGrid([
      ['File name', fileName],
      ['File size', fileSize],
      ['Triangles', this.formatInteger(report['triangleCount'])],
      [
        'Dimensions',
        `${this.formatNumber(dimensions?.['width'])} × ${this.formatNumber(dimensions?.['height'])} × ${this.formatNumber(dimensions?.['depth'])} model units`,
      ],
      [
        'Surface area',
        `${this.formatNumber(report['surfaceArea'])} square model units`,
      ],
      ['Volume', `${this.formatNumber(report['volume'])} cubic model units`],
      [
        'Connected components',
        typeof componentCount === 'number' &&
        Number.isInteger(componentCount) &&
        componentCount >= 0
          ? componentCount === 1
            ? '1 connected component'
            : `${this.formatInteger(componentCount)} separate components`
          : '—',
      ],
    ]);

    heading('Validation findings');
    writeLines(
      'This report checks mesh validation only. Printer settings, material, wall thickness and STL units are outside the current checks.',
      { color: [82, 96, 87], fontSize: 9 },
    );

    if (passed && issues.length === 0) {
      writeLines('No mesh validation issues found.', { fontSize: 10 });
    } else if (issues.length > 0) {
      for (const issue of issues) {
        writeLines(`• ${issue.label}`, { fontSize: 10, style: 'bold' });
        if (issue.detail) {
          writeLines(issue.detail, {
            color: [82, 96, 87],
            fontSize: 9,
            indent: 4,
          });
        }
        const guidance = guidanceForIssues([issue])[0];
        if (guidance) {
          writeLines(`Suggested repair: ${guidance.nextSteps[0]}`, {
            color: [82, 96, 87],
            fontSize: 9,
            indent: 4,
          });
        }
        cursorY += 2;
      }
    } else {
      writeLines(
        'The model failed validation, but no issue details were supplied.',
        {
          fontSize: 10,
        },
      );
    }

    heading('Technical details');
    if (boundingBox) {
      metricGrid([
        [
          'X range',
          `${this.formatNumber(boundingBox['minX'])} to ${this.formatNumber(boundingBox['maxX'])}`,
        ],
        [
          'Y range',
          `${this.formatNumber(boundingBox['minY'])} to ${this.formatNumber(boundingBox['maxY'])}`,
        ],
        [
          'Z range',
          `${this.formatNumber(boundingBox['minZ'])} to ${this.formatNumber(boundingBox['maxZ'])}`,
        ],
      ]);
    } else {
      writeLines('Bounding-box values were not supplied.', { fontSize: 10 });
    }

    const pageCount = pdf.getNumberOfPages();
    for (let pageNumber = 1; pageNumber <= pageCount; pageNumber++) {
      pdf.setPage(pageNumber);
      addFooter(pageNumber, pageCount);
    }
    return { fileName: this.downloadFileName(fileName), pdf };
  }

  private formatNumber(value: unknown, maximumFractionDigits = 2): string {
    return typeof value === 'number' && Number.isFinite(value)
      ? new Intl.NumberFormat('en', { maximumFractionDigits }).format(value)
      : '—';
  }

  private formatInteger(value: unknown): string {
    return this.formatNumber(value, 0);
  }

  private formatFileSize(value: unknown): string {
    if (typeof value !== 'number' || !Number.isFinite(value) || value < 0) {
      return '—';
    }
    const units = ['bytes', 'KB', 'MB', 'GB'];
    let size = value;
    let unit = 0;
    while (size >= 1024 && unit < units.length - 1) {
      size /= 1024;
      unit += 1;
    }
    return `${this.formatNumber(size, unit === 0 ? 0 : 1)} ${units[unit]}`;
  }

  private downloadFileName(fileName: string): string {
    const safeStem = fileName
      .replace(/\.stl$/i, '')
      .trim()
      .normalize('NFKD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-zA-Z0-9_-]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 100);
    return `${safeStem || 'model'}-quality-report.pdf`;
  }

  private stringValue(value: unknown): string {
    return typeof value === 'string' ? value.trim() : '';
  }

  private asRecord(value: unknown): ReportRecord | null {
    return typeof value === 'object' && value !== null && !Array.isArray(value)
      ? (value as ReportRecord)
      : null;
  }
}
