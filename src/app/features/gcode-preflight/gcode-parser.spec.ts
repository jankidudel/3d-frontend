import {
  GcodeParseError,
  buildVolumeMessage,
  dimensions,
  layerMoveCounts,
  parseGcode,
} from './gcode-parser';
import { commonGcodeFixture } from './fixtures/common-gcode.fixture';

describe('parseGcode', () => {
  it('tracks modes, resets, extrusion and metadata', () => {
    const report = parseGcode(commonGcodeFixture);
    expect(report.metadata.slicer).toBe('Cura_SteamEngine 5.8');
    expect(report.metadata.declaredLayers).toBe(2);
    expect(report.metadata.hasThumbnail).toBe(true);
    expect(report.extrusionMoves).toBe(3);
    expect(report.travelMoves).toBe(1);
    expect(report.extents?.max.x).toBe(11);
    expect(report.hotendTargets).toEqual(
      expect.arrayContaining([
        expect.objectContaining({ value: 210, waiting: false }),
        expect.objectContaining({ value: 215, waiting: true }),
      ]),
    );
    expect(report.bedTargets).toEqual(
      expect.arrayContaining([
        expect.objectContaining({ value: 60, waiting: false }),
        expect.objectContaining({ value: 65, waiting: true }),
      ]),
    );
    expect(report.layers).toHaveLength(2);
  });
  it('applies G92 XYZ resets before subsequent absolute motion', () => {
    const report = parseGcode(
      'G90\nG1 X10 Y10 Z1 E1\nG92 X0 Y0 Z0\nG1 X2 Y3 Z4 E2',
    );
    expect(report.extents?.max).toEqual({ x: 10, y: 10, z: 4 });
  });
  it('converts inch coordinates and keeps travel separate', () => {
    const report = parseGcode('G20\nG90\nM82\nG0X1Y1\nG1X2E1');
    expect(report.extents?.max.x).toBeCloseTo(50.8);
    expect(report.travelMoves).toBe(1);
    expect(dimensions(report.extents!).x).toBeCloseTo(50.8);
  });
  it('reports malformed lines and limitations', () => {
    expect(() => parseGcode('G1 Xbroken')).toThrow(GcodeParseError);
    const report = parseGcode('G1 X1\nG2 X2\nM900 K0.05');
    expect(report.limitations.join(' ')).toContain('Arc moves');
    expect(report.limitations.join(' ')).toContain('M900');
  });
  it('compares parsed extents without claiming compatibility', () => {
    const report = parseGcode('G1 X20 Y20 Z20 E1');
    expect(buildVolumeMessage(report, { x: 10, y: 30, z: 30 })).toContain(
      'outside the entered coordinate bounds',
    );
  });
  it('counts extrusion and travel moves for the selected viewer layer', () => {
    const report = parseGcode(commonGcodeFixture);
    expect(layerMoveCounts(report.layers[0])).toEqual({
      extrusion: 2,
      travel: 1,
    });
  });
});

describe('G-code evidence contract', () => {
  it('keeps original source lines across CRLF, blanks and comment lines', () => {
    const report = parseGcode(
      '; heading\r\n\r\nG21\r\nG90\r\nM82\r\nG1 X10 E1\r\nG92 E0\r\nG1 X20 E1',
    );
    expect(report.layers[0].paths.map((path) => path.line)).toEqual([6, 8]);
    expect(
      report.findings.find((item) => item.command === 'G92')?.samples[0],
    ).toMatchObject({ line: 7, excerpt: 'G92 E0' });
    expect(report.extrusionMoves).toBe(2);
  });
  it('distinguishes absolute equal E from incremental E and resets', () => {
    const base =
      'G21\nG90\nMODE\nG92 E0\nG1 X10 Y10 Z0.2 E1\nG1 X20 Y10 E1\nG92 E0\nG1 X30 Y10 E1';
    const absolute = parseGcode(base.replace('MODE', 'M82'));
    const relative = parseGcode(base.replace('MODE', 'M83'));
    expect(absolute.extrusionMoves).toBe(2);
    expect(absolute.travelMoves).toBe(1);
    expect(relative.extrusionMoves).toBe(3);
    expect(relative.travelMoves).toBe(0);
    expect(absolute.layers[0].paths).toHaveLength(3);
  });
  it('discloses firmware-dependent E transitions while preserving linear metric', () => {
    const report = parseGcode('M83\nG90\nG1 X20 E1');
    expect(report.coverage.linear).toBe('recognised');
    expect(report.coverage.extrusion).toBe('incomplete');
    expect(report.limitations.join(' ')).toContain('firmware-dependent');
    expect(parseGcode('G91\nM82\nG1 X1 E1\nG1 X1 E1').coverage.extrusion).toBe(
      'incomplete',
    );
  });
  it('preserves a supported time declaration with unsupported path effects', () => {
    const report = parseGcode(
      '; generated by PrusaSlicer 2.9.6\n; estimated printing time (normal mode) = 1h 30m 0s\nG1 X1\nG2 X20 I5 J5\nCUSTOM_START',
    );
    expect(report.duration?.value).toBe(1.5);
    expect(report.coverage.duration).toBe('recognised');
    expect(report.coverage.linear).toBe('incomplete');
    expect(report.coverage.extrusion).toBe('incomplete');
    expect(report.counts.unsupported).toBe(2);
    expect(
      report.findings.find((item) => item.command === 'arcs')?.firstLine,
    ).toBe(4);
  });
  it('classifies known fan commands separately from unsupported tools and volumetric units', () => {
    const auxiliary = parseGcode('G1 X1\nM106 S128\nM107');
    expect(auxiliary.coverage.linear).toBe('recognised');
    expect(auxiliary.counts.auxiliary).toBe(2);
    for (const unsupported of [
      'T0',
      'T1',
      'M200 D1.75',
      'G54',
      'SET_GCODE_OFFSET X=20',
    ]) {
      const report = parseGcode(`G1 X1\n${unsupported}\nG1 X2 E1`);
      expect(report.coverage.linear).toBe('incomplete');
    }
  });
  it('never fabricates zero for missing, vector, repeated or conflicting declarations', () => {
    const prefix = '; generated by PrusaSlicer 2.9.6\n';
    for (const metadata of [
      '',
      '; filament used [g] = 2, 3',
      '; filament used [g] = 0',
      '; filament used [g] = 2\n; filament used [g] = broken',
      '; generated by OtherSlicer\n; filament used [g] = 2',
      '; estimated printing time (normal mode) = 1h\n; estimated printing time (normal mode) = unknown',
      '; estimated printing time (normal mode) = 1h 1h',
      '; estimated printing time (normal mode) = 30m 1h',
    ]) {
      const report = parseGcode(prefix + metadata + '\nG1 X1');
      expect(report.material).toBeNull();
      expect(report.duration).toBeNull();
    }
    const mass = parseGcode(prefix + '; filament used [g] = 12.5\nG1 X1');
    expect(mass.material?.value).toBe(12.5);
    expect(mass.material?.unit).toBe('g');
    const tools = parseGcode(
      prefix + '; filament used [g] = 12.5\nG1 X1\nT0\nT1',
    );
    expect(tools.material).toBeNull();
    const length = parseGcode(prefix + '; filament used [mm] = 1200\nG1 X1');
    expect(length.material).toBeNull();
  });
  it('separates linear/travel and extrusion envelopes with actual location', () => {
    const report = parseGcode(
      'G21\nG90\nM82\nG0 X10 Y20 Z0.2\nG1 X110 Y120 Z20 E1\nG0 X230',
    );
    expect(report.extrusionExtents).toEqual({
      min: { x: 10, y: 20, z: 0.2 },
      max: { x: 110, y: 120, z: 20 },
    });
    expect(report.extents?.max.x).toBe(230);
    expect(buildVolumeMessage(report, { x: 220, y: 220, z: 200 })).toContain(
      'outside',
    );
    const shifted = parseGcode('G0 X230\nG1 X240 E1');
    expect(shifted.extrusionExtents?.max.x).toBe(240);
    expect(dimensions(shifted.extrusionExtents!).x).toBe(10);
    expect(buildVolumeMessage(shifted, { x: 220, y: 220, z: 200 })).toContain(
      'outside',
    );
  });
  it('fails malformed and nonfinite fields and separates empty/comments-only failures', () => {
    for (const text of [
      'G1 XNaN',
      'G1 XInfinity',
      'G1 X' + '9'.repeat(400),
      '',
      '; only comments\n\n',
      'BGCODE\u0000',
      'G1 ' + 'X1 '.repeat(2000),
    ]) {
      expect(() => parseGcode(text)).toThrow(GcodeParseError);
    }
    const relative = parseGcode(
      'G21\nG91\nM83\nG1 X1 Y2 Z3 E1\nG1 X2 Y3 Z4 E1',
    );
    expect(relative.extents?.max).toEqual({ x: 3, y: 5, z: 7 });
  });
  it('bounds repeated source evidence and discloses preview/source limits separately', () => {
    const repeated = parseGcode(
      'G1 X1\n' +
        ('G2 X20 I1 J2 ; ' + '<script>'.repeat(100) + '\n').repeat(1000),
    );
    const arcs = repeated.findings.find((item) => item.command === 'arcs')!;
    expect(arcs.count).toBe(1000);
    expect(arcs.firstLine).toBe(2);
    expect(arcs.lastLine).toBe(1001);
    expect(arcs.samples).toHaveLength(3);
    expect(arcs.samples.every((sample) => sample.excerpt.length <= 240)).toBe(
      true,
    );
    const preview = parseGcode('G91\n' + 'G1 X1\n'.repeat(50_001));
    expect(preview.previewTruncated).toBe(true);
    expect(preview.layers[0].paths).toHaveLength(50_000);
    expect(preview.extents?.max.x).toBe(50_001);
    expect(preview.coverage.linear).toBe('recognised');
    const partial = parseGcode('G91\n' + 'G1 X1\n'.repeat(200_001));
    expect(partial.counts.reviewedLines).toBe(200_000);
    expect(partial.coverage.linear).toBe('incomplete');
    expect(partial.duration).toBeNull();
  });
  it('retains late maximum temperature targets beyond evidence sampling', () => {
    const report = parseGcode(
      'G1 X1\n' + 'M104 S100\n'.repeat(110) + 'M104 S290',
    );
    expect(report.hotendTargets.length).toBeLessThanOrEqual(100);
    expect(
      Math.max(...report.hotendTargets.map((target) => target.value)),
    ).toBe(290);
  });
});
