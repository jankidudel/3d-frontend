import { TestBed } from '@angular/core/testing';
import { provideRouter } from '@angular/router';
import { GcodePreflightPage } from './gcode-preflight-page';
import { parseGcode, coordinateMessage, GcodeCoverage } from './gcode-parser';
import { AnalyticsService } from '../../core/analytics/analytics.service';
import { SeoService } from '../../core/seo/seo.service';
import {
  JobPlanningSession,
  PlanningDestination,
} from '../planning/job-planning-session';

class ControlledWorker {
  static instances: ControlledWorker[] = [];
  listeners = new Map<string, (event: unknown) => void>();
  terminated = false;
  constructor() {
    ControlledWorker.instances.push(this);
  }
  addEventListener(type: string, listener: (event: unknown) => void) {
    this.listeners.set(type, listener);
  }
  postMessage() {
    /* Test controls completion ordering independently. */
  }
  terminate() {
    this.terminated = true;
  }
  finish(text: string) {
    this.listeners.get('message')?.({ data: { report: parseGcode(text) } });
  }
}
function setup() {
  TestBed.configureTestingModule({
    imports: [GcodePreflightPage],
    providers: [
      provideRouter([]),
      {
        provide: AnalyticsService,
        useValue: {
          trackGcodeUploadStarted: vi.fn(),
          trackGcodeParsed: vi.fn(),
          trackGcodeLimitationShown: vi.fn(),
        },
      },
      { provide: SeoService, useValue: { apply: vi.fn() } },
    ],
  });
  ControlledWorker.instances = [];
  vi.stubGlobal('Worker', ControlledWorker);
  return TestBed.createComponent(GcodePreflightPage);
}
afterEach(() => vi.unstubAllGlobals());

it('terminates A and suppresses late results after loading B', async () => {
  const fixture = setup();
  const page = fixture.componentInstance;
  const a = page.loadFile(new File(['G1 X10'], 'A.gcode'));
  await vi.waitFor(() => expect(ControlledWorker.instances).toHaveLength(1));
  const old = ControlledWorker.instances[0];
  const b = page.loadFile(new File(['G1 X20'], 'B.gcode'));
  await vi.waitFor(() => expect(ControlledWorker.instances).toHaveLength(2));
  expect(old.terminated).toBe(true);
  ControlledWorker.instances[1].finish('G1 X20');
  await b;
  old.finish('G1 X10');
  await a;
  expect(page.file()?.name).toBe('B.gcode');
  expect(page.report()?.extents?.max.x).toBe(20);
  expect(page.error()).toBe('');
  expect(page.parsing()).toBe(false);
  fixture.destroy();
});
it('cancels a worker and invalidates reviewed estimates and source evidence', async () => {
  const fixture = setup();
  const page = fixture.componentInstance;
  page.reviewed.set(true);
  page.reviewedHours.set(5);
  page.evidence.set({ line: 1, excerpt: 'old' });
  const load = page.loadFile(new File(['G1 X10'], 'cancel.gcode'));
  await vi.waitFor(() => expect(ControlledWorker.instances).toHaveLength(1));
  page.cancel();
  await load;
  expect(ControlledWorker.instances[0].terminated).toBe(true);
  expect(page.report()).toBeNull();
  expect(page.evidence()).toBeNull();
  expect(page.reviewed()).toBe(false);
  expect(page.reviewedHours()).toBeNull();
  const session = TestBed.inject(JobPlanningSession);
  await page.offer(PlanningDestination.Finish);
  expect(session.hasOffer(PlanningDestination.Finish)).toBe(false);
  fixture.destroy();
});
it('records assumptions and deliberate edits without raw paths, and rejects reversed/blank bounds', () => {
  const fixture = setup();
  const page = fixture.componentInstance;
  const report = parseGcode(
    '; generated by PrusaSlicer 2.9.6\n; estimated printing time (normal mode) = 1h\nG1 X10 E1',
  );
  page.report.set(report);
  page.file.set(new File(['G1 X10'], '<label>.gcode'));
  page.reviewedHours.set(2);
  page.reviewed.set(true);
  page.buildX.set(220);
  page.buildY.set(220);
  page.buildZ.set(200);
  const record = JSON.parse(page.recordSummary());
  expect(record.file.label).toBe('<label>.gcode');
  expect(record.estimateReview).toMatchObject({
    hours: 2,
    editedHours: true,
    confirmed: true,
  });
  expect(record.report.layers).toBeUndefined();
  expect(record.report.assumptions.length).toBeGreaterThan(0);
  const shifted = {
    min: { x: 180, y: 10, z: 1 },
    max: { x: 280, y: 20, z: 2 },
  };
  expect(
    coordinateMessage(
      shifted,
      { min: { x: 170, y: 0, z: 0 }, max: { x: 300, y: 100, z: 100 } },
      GcodeCoverage.Recognised,
    ),
  ).toContain('within');
  expect(
    coordinateMessage(
      shifted,
      { min: { x: 300, y: 0, z: 0 }, max: { x: 170, y: 100, z: 100 } },
      GcodeCoverage.Recognised,
    ),
  ).toBeNull();
  page.minX.set(NaN);
  expect(page.volumeMessage()).toBeNull();
  fixture.destroy();
});

